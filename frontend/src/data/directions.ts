/** Bir jónelistiń bar barlıq "juwapker/múddet/orınlanıw" arqalı esaplanatuǵın
 * "atomar" bólimleri: kishi kórsetkishi bar tiykarǵı bólim ushın soл kishi
 * kórsetkishler, joq болса tiykarǵы bólimniń ózi (admin panelindegi
 * `DirectionsAdmin`-de qollanıladı — iyerarxiya kartalarǵа emes, tolıq
 * dizimge kerek bolǵanda). */
export interface DirectionLeafBlock {
  id: string;
  text: string;
  ownerGroup: string | null;
  parentText: string | null;
}

export function directionLeafBlocks(direction: Direction): DirectionLeafBlock[] {
  return direction.blocks.flatMap((b): DirectionLeafBlock[] =>
    b.subBlocks && b.subBlocks.length > 0
      ? b.subBlocks.map((s) => ({
          id: s.id,
          text: s.text,
          ownerGroup: s.ownerGroup,
          parentText: b.text,
        }))
      : [{ id: b.id, text: b.text, ownerGroup: b.ownerGroup, parentText: null }],
  );
}
